const {chromium}=require('playwright');
const path=require('path');
(async()=>{
  const b=await chromium.launch();
  const ctx=await b.newContext({viewport:{width:1440,height:900},deviceScaleFactor:2});
  const p=await ctx.newPage();
  p.on('pageerror',e=>console.log('PAGE-ERR:',e.message));
  p.on('console',m=>{if(m.type()==='error')console.log('CONSOLE-ERR:',m.text());});
  const abs=path.resolve('demo-system.html').replace(/\\/g,'/');
  await p.goto('file://'+abs,{waitUntil:'load'});
  await p.waitForTimeout(500);
  await p.evaluate(()=>YX.nav('a2'));
  await p.waitForTimeout(300);
  await p.evaluate(()=>YX.openSheet('sh_plan'));
  await p.waitForTimeout(500);
  await p.screenshot({path:'shots/demo-x1.png'});
  console.log('SHOT x1');
  await p.evaluate(()=>YX.closeSheet());
  await p.waitForTimeout(400);
  await p.evaluate(()=>YX.nav('a4'));
  await p.waitForTimeout(300);
  await p.evaluate(()=>YX.openSheet('sh_ev'));
  await p.waitForTimeout(500);
  await p.screenshot({path:'shots/demo-x2.png'});
  console.log('SHOT x2');
  await b.close();
})().catch(e=>{console.error('FAIL',e);process.exit(1);});